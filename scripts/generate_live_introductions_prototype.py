        "<section><h2>Accessibility</h2>"
        f"<p>{escape(contract.accessibility)}</p></section>"
        "<section><h2>Failure / exit behavior</h2>"
        f"<p>{escape(contract.failure_exit)}</p></section>"
        "<section><h2>Transition semantics</h2>"
        "<p>Only typed navigation edges with distinct, non-atlas destinations "
        "are links. Self-targets, atlas-target mutations, unsupported mutations, "
        "automatic outcomes, and review edges are labeled noninteractive states. "
        "A guarded continuation links only on its direct normal-completion variant.</p>"
        f"<p>Terminal class: {escape(frame.terminal_class.value.replace('_', ' '))}. "
